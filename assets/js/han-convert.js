  var MAP = Object.create(null);
  for (var i = 0; i < TABLE.length; i += 8) {
    MAP[parseInt(TABLE.substr(i, 4), 16)] = String.fromCharCode(
      parseInt(TABLE.substr(i + 4, 4), 16),
    );
  }

  var SKIP = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1, KBD: 1, SAMP: 1, TEXTAREA: 1 };
  var root = document.documentElement;
  var LANG_DEFAULT =
    root.getAttribute("data-han-lang") || root.getAttribute("lang") || "";

  function convert(text) {
    var out = "";
    for (var i = 0; i < text.length; i++) {
      var c = text.charCodeAt(i);
      out += MAP[c] || text.charAt(i);
    }
    return out;
  }

  function prefersSimplified() {
    var languages = navigator.languages || [navigator.language || ""];
    var tag = String(languages[0] || "").toLowerCase();
    if (tag.indexOf("zh") !== 0) return false;
    if (tag.indexOf("hant") !== -1 || /-(tw|hk|mo)(-|$)/.test(tag)) return false;
    return true;
  }

  function mode() {
    if (window.__hanMode === "s" || window.__hanMode === "t") return window.__hanMode;
    var saved = null;
    try {
      saved = localStorage.getItem("han");
    } catch (e) {
      // localStorage 可能不可用（隱私模式、封鎖 cookie）
    }
    window.__hanMode =
      saved === "s" || saved === "t" ? saved : prefersSimplified() ? "s" : "t";
    return window.__hanMode;
  }

  function eachTextNode(fn) {
    if (!document.body) return;
    var walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      null,
      false,
    );
    for (var node = walker.nextNode(); node; node = walker.nextNode()) {
      var parent = node.parentNode;
      if (!parent || !parent.nodeName || SKIP[parent.nodeName]) continue;
      if (parent.closest && parent.closest("[data-han-keep]")) continue;
      fn(node);
    }
  }

  var titleOriginal = null;

  function toSimplified() {
    eachTextNode(function (node) {
      // 原字串留存一份，切回繁體時據以還原（不再走反向對照表）。
      if (node.__hanOriginal === undefined) node.__hanOriginal = node.nodeValue;
      node.nodeValue = convert(node.__hanOriginal);
    });
    if (titleOriginal === null) titleOriginal = document.title;
    document.title = convert(titleOriginal);
  }

  function toOriginal() {
    eachTextNode(function (node) {
      if (node.__hanOriginal !== undefined) node.nodeValue = node.__hanOriginal;
    });
    if (titleOriginal !== null) document.title = titleOriginal;
  }

  var button = document.querySelector(".han-toggle");

  function paint(m) {
    if (!button) return;
    var i18n = (window.ui && window.ui.i18n) || {};
    var simplified = m === "s";
    var label = simplified ? "简" : "繁";
    var text =
      (simplified ? i18n.han_simplified : i18n.han_traditional) ||
      (simplified ? "Simplified Chinese" : "Traditional Chinese");
    var span = button.querySelector(".han-toggle-label");
    if (span) span.textContent = label;
    button.setAttribute("title", text);
    button.setAttribute("aria-label", text);
    button.setAttribute("aria-pressed", simplified ? "true" : "false");
  }

  function apply(m) {
    window.__hanMode = m;
    if (m === "s") toSimplified();
    else toOriginal();
    root.setAttribute("lang", m === "s" ? "zh-Hans" : LANG_DEFAULT);
    if (m === "s") root.classList.add("han-s");
    else root.classList.remove("han-s");
    paint(m);
  }

  if (button) {
    button.addEventListener("click", function () {
      var next = mode() === "s" ? "t" : "s";
      try {
        localStorage.setItem("han", next);
      } catch (e) {
        // 同上：無法保存時僅本次生效
      }
      apply(next);
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      apply(mode());
    });
  } else {
    apply(mode());
  }
